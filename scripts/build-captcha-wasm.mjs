// Compiles src/heist/captcha/captchaKernel.c to WebAssembly (SIMD) and writes
// src/heist/captcha/captchaKernelWasm.js with the bytes as base64, so the single-file build
// needs no separate .wasm file. Run after editing the C file: npm run build:captcha-wasm
// Needs clang with the wasm32 target and wasm-ld (LLVM).
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdtempSync, rmSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { tmpdir } from 'node:os';
import { fileURLToPath } from 'node:url';

const dir = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'heist', 'captcha');
const tmp = mkdtempSync(join(tmpdir(), 'captcha-wasm-'));
const out = join(tmp, 'kernel.wasm');
try {
  execFileSync('clang', [
    '--target=wasm32', '-O3', '-msimd128', '-nostdlib', '-ffreestanding',
    '-Wl,--no-entry', '-Wl,--import-memory', '-Wl,--export=__heap_base', '-Wl,--strip-all',
    '-o', out, join(dir, 'captchaKernel.c'),
  ], { stdio: 'inherit' });
  const b64 = readFileSync(out).toString('base64');
  writeFileSync(join(dir, 'captchaKernelWasm.js'),
    '// Generated by scripts/build-captcha-wasm.mjs from captchaKernel.c — do not edit.\n' +
    `export const CAPTCHA_KERNEL_WASM = '${b64}';\n`);
  console.log(`captchaKernelWasm.js: ${readFileSync(out).length} bytes of wasm`);
} finally {
  rmSync(tmp, { recursive: true, force: true });
}
