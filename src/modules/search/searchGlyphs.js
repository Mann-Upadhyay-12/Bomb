// Word Search letters by template matching against letters cut from real game screenshots.
// The game always draws the grid in the same font at the same place, so comparing shapes is far more
// reliable than general OCR for the letters we have samples of (Tesseract read W as J, N/H/M as Z…).
// Letters with no sample yet fall through to Tesseract (see search/index.jsx).
import { getSearchGrid } from './searchOCR.js';

export const GLYPH_N = 16; // feature grid size

/**
 * Shape of the letter in one grid cell: the bright letter strokes inside the tile, cropped to their
 * bounding box and resampled to GLYPH_N×GLYPH_N coverage (0..1), plus the box's aspect ratio.
 * @returns {{ v: Float32Array, aspect: number, hRel: number } | null}  null = empty / unreadable cell
 */
export function cellFeature(data, W, H, r, c) {
  const { rowCenters, colCenters, cellW, cellH } = getSearchGrid(W, H);
  const cw = Math.round(cellW * 0.86), ch = Math.round(cellH * 0.86);
  const x0 = Math.max(0, Math.round(colCenters[c] - cw / 2)), y0 = Math.max(0, Math.round(rowCenters[r] - ch / 2));
  const w = Math.min(W - x0, cw), h = Math.min(H - y0, ch);
  if (w < 6 || h < 6) return null;

  const L = new Float32Array(w * h);
  const sorted = [];
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
    const i = ((y0 + y) * W + x0 + x) * 4;
    const v = 0.299 * data[i] + 0.587 * data[i + 1] + 0.114 * data[i + 2];
    L[y * w + x] = v; sorted.push(v);
  }
  sorted.sort((a, b) => a - b);
  const lo = sorted[sorted.length >> 1], hi = sorted[Math.floor(sorted.length * 0.985)];
  if (hi - lo < 60) return null; // no bright letter
  const thr = lo + 0.5 * (hi - lo);

  // letter = bright pixels; ignore the tile border by dropping ink that touches the crop edge
  const ink = new Uint8Array(w * h);
  for (let i = 0; i < w * h; i++) ink[i] = L[i] >= thr ? 1 : 0;
  const lab = new Int32Array(w * h), keep = [];
  let next = 0;
  const stack = [];
  for (let s = 0; s < w * h; s++) {
    if (!ink[s] || lab[s]) continue;
    next++; let edge = false, area = 0; stack.push(s); lab[s] = next;
    while (stack.length) {
      const p = stack.pop(), px = p % w, py = (p / w) | 0; area++;
      if (px === 0 || py === 0 || px === w - 1 || py === h - 1) edge = true;
      for (let dy = -1; dy <= 1; dy++) for (let dx = -1; dx <= 1; dx++) {
        const nx = px + dx, ny = py + dy;
        if (nx < 0 || ny < 0 || nx >= w || ny >= h) continue;
        const q = ny * w + nx;
        if (ink[q] && !lab[q]) { lab[q] = next; stack.push(q); }
      }
    }
    keep[next] = !edge && area >= 3;
  }
  let bx0 = w, by0 = h, bx1 = -1, by1 = -1;
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
    if (keep[lab[y * w + x]]) { if (x < bx0) bx0 = x; if (x > bx1) bx1 = x; if (y < by0) by0 = y; if (y > by1) by1 = y; }
  }
  if (bx1 < 0) return null;
  const bw = bx1 - bx0 + 1, bh = by1 - by0 + 1;

  // soft coverage: brightness above the threshold, area-sampled into the grid
  const v = new Float32Array(GLYPH_N * GLYPH_N);
  const span = hi - thr || 1;
  for (let gy = 0; gy < GLYPH_N; gy++) for (let gx = 0; gx < GLYPH_N; gx++) {
    const sx0 = bx0 + gx * bw / GLYPH_N, sx1 = bx0 + (gx + 1) * bw / GLYPH_N;
    const sy0 = by0 + gy * bh / GLYPH_N, sy1 = by0 + (gy + 1) * bh / GLYPH_N;
    let sum = 0, n = 0;
    for (let y = Math.floor(sy0); y < Math.ceil(sy1); y++) for (let x = Math.floor(sx0); x < Math.ceil(sx1); x++) {
      const p = y * w + x;
      const cov = keep[lab[p]] ? Math.min(1, Math.max(0, (L[p] - thr) / span + 0.5)) : 0;
      sum += cov; n++;
    }
    v[gy * GLYPH_N + gx] = n ? sum / n : 0;
  }
  return { v, aspect: bw / bh, hRel: bh / cellH };
}

function corr(a, b) {
  let ma = 0, mb = 0;
  for (let i = 0; i < a.length; i++) { ma += a[i]; mb += b[i]; }
  ma /= a.length; mb /= b.length;
  let sab = 0, saa = 0, sbb = 0;
  for (let i = 0; i < a.length; i++) { const x = a[i] - ma, y = b[i] - mb; sab += x * y; saa += x * x; sbb += y * y; }
  return saa && sbb ? sab / Math.sqrt(saa * sbb) : 0;
}

/** Similarity 0..1 of a cell to one template: shape correlation, minus a penalty for a different width/height. */
export function glyphScore(f, t) {
  return corr(f.v, t.v) - 0.6 * Math.abs(Math.log(f.aspect / t.aspect));
}

export function decodeTemplates(bank) {
  const out = {};
  for (const [k, t] of Object.entries(bank)) {
    out[k] = { aspect: t.a, v: Float32Array.from(t.v, ch => Number(ch) / 9) };
  }
  return out;
}

/**
 * Best letter for a cell. `sure` = the match is clearly better than any other letter and close to the
 * sample — then it is used without OCR.
 * @returns {{ letter, score, margin, sure }}
 */
export function matchGlyph(f, templates) {
  if (!f) return { letter: '', score: 0, margin: 0, sure: false };
  let best = null, second = null;
  for (const [k, t] of Object.entries(templates)) {
    const s = glyphScore(f, t);
    if (!best || s > best.s) { second = best; best = { k, s }; }
    else if (!second || s > second.s) second = { k, s };
  }
  if (!best) return { letter: '', score: 0, margin: 0, sure: false };
  const margin = best.s - (second ? second.s : 0);
  // sure = close to the sample and clearly ahead of the next letter, or far ahead of every other letter.
  // (Letters with no sample — B, I, Q — score ≤ 0.67 with a small lead in tests, so they're never "sure".)
  const sure = (best.s >= 0.80 && margin >= 0.06) || (best.s >= 0.68 && margin >= 0.35);
  return { letter: best.k, score: best.s, margin, sure };
}

/**
 * Final letter from the shape match + Tesseract (only asked when the shape match isn't sure).
 * Tesseract wins for letters we have no sample of, and when the shape agrees well enough with its
 * letter; when the shape clearly says otherwise (W read as J, N/H/M read as Z…), the shape wins.
 */
export function combineGlyphOcr(f, m, ocrLetter, templates) {
  if (!ocrLetter || ocrLetter === '?') return m.letter || '?';
  if (!f || !m.letter) return ocrLetter;
  const t = templates[ocrLetter];
  if (!t) return ocrLetter; // no sample of that letter (B, I, Q …)
  return glyphScore(f, t) >= m.score - 0.12 ? ocrLetter : m.letter;
}

